package OOPsConcept;

// Class and Object (Creating an Object)

public class Student {
    // Attributes
    public int id;
    public int age;
    public String name;
    public int nos;

    // Constructor
    public Student() {
        System.out.println("Student default constructor called");
    }

    // Methods or Behavior
    public void study() {
        System.out.println("Studying");
    }
    public void sleep() {
        System.out.println("Sleeping");
    }
    public void bunk() {
        System.out.println("Bunking");
    }

    static void main() {

    }
}
